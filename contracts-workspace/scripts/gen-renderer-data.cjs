/**
 * Generates the packed `bytes constant CODES` and `bytes constant NAMES`
 * + a name-offset table for LegendRenderer.sol from countries.json + fifa-codes.js.
 *
 * Prints Solidity source snippets to stdout — copy/paste into the contract,
 * or run with `--write` to overwrite the inline constants section.
 */

const fs = require('fs');
const path = require('path');
const COUNTRIES = require('../data/countries.json');
const { codes } = require('../data/fifa-codes.js');

if (COUNTRIES.length !== 211) throw new Error('expected 211 countries');
if (codes.length !== 211) throw new Error('expected 211 codes');

// 1) CODES — 211 × 3 = 633 bytes
const codesHex = codes.map((c) => Buffer.from(c).toString('hex')).join('');

// 2) NAMES — pack ASCII bytes contiguously; produce an offset table
const offsets = [];
const namesBuf = [];
let off = 0;
for (const c of COUNTRIES) {
  // Strip diacritics so we stay ASCII-safe in the SVG text node.
  const ascii = c.name.normalize('NFD').replace(/[̀-ͯ]/g, '');
  offsets.push(off);
  namesBuf.push(Buffer.from(ascii, 'utf8'));
  off += ascii.length;
}
const namesHex = Buffer.concat(namesBuf).toString('hex');

console.log('// Auto-generated by scripts/gen-renderer-data.cjs');
console.log(`bytes private constant CODES = hex"${codesHex}";`);
console.log(`bytes private constant NAMES = hex"${namesHex}";`);
console.log('uint16[212] private constant NAME_OFFSETS = [');
for (let i = 0; i < offsets.length; i += 8) {
  console.log('    ' + offsets.slice(i, i + 8).join(', ') + ',');
}
console.log(`    ${off}  // end sentinel`);
console.log('];');

if (process.argv.includes('--write')) {
  const out = path.join(__dirname, '..', 'data', 'renderer-data.json');
  fs.writeFileSync(out, JSON.stringify({ codesHex, namesHex, offsets: [...offsets, off] }, null, 2));
  console.log('\nWrote', out);
}
